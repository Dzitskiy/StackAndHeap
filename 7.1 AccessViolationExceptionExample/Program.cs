using System;

unsafe // Необходимо для использования небезопасного кода
{
    // Создаем массив байт, выделяя память
    byte[] data = new byte[10];

    // Получаем указатель на начало массива
    fixed (byte* ptr = data)
    {
        // Попытка записи за пределы массива (например, по смещению 100)
        // Это приведет к AccessViolationException
        // Раскомментировать
        *(ptr + 10/*00000*/) = 0x00; // Недействительный адрес памяти
    }
}